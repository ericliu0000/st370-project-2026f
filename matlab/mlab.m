% Alphabetized List of the Most Important Functions Used in M-Lab
%
% bplot                makes one or more boxplots
% clf                  clears figure (useful after subplot)
% diary                makes text listing of MATLAB session
% exppdf               exponential density function
% expcdf               exponential cumulative distribution
% exprnd               generates exponential random variables
% figure               creates new plot window
% help                 displays function help files
% hist                 makes histogram of a data vector
% hplot                histogram with y scale in probability units
% load                 uploads to memory .mat files
% lplot                allows character variable in x position
% lm                   least squares program for linear models
% means                mean of a variable by levels of other variables
% mfit                 fitted effects for factorial experiments
% mplot                plot of means by levels of other variables
% normpdf              normal density function
% normcdf              normal cumulative distribution
% normrnd              generates normal random variables
% path                 shows directories that are currently accessible
% plot                 creates scatterplot (x-y plot)
% quantile             gives interpolated quantile estimate
% read                 interactive method for reading in data
% readfile             reads data from a file (also file2struct)
% sample               random samples and permutations
% save                 saves work for future use
% stats                basic statistics for one or more vectors
% struct2file          writes text file of struct
% subplot              creates multiple plots in one window
% subset               creates subsets of structs
% text                 adds text to a plot
% title                adds title to a plot
% viewdata             lists contents of structure arrays
% who,whos             lists objects currently in memory
% xlabel               adds x label to a plot
% ylabel               adds y label to a plot
%
% To find out more about one of these functions type
% help functionname; for example, help plot or help lm.
